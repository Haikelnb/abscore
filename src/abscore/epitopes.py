#: Percentile-rank cutoff for calling a peptide a binder. Rank rather than
#: predicted affinity, because each allele's score distribution differs, so one
#: nanomolar cutoff is not comparable across alleles while one rank cutoff is.
#:
#: 10.0 is the cutoff used in the BioPhi paper's MHC II analysis ("predicted
#: below 10 percentile in any of" its eight alleles), which is why it is the
#: default here -- it keeps counts comparable to that published analysis.
#:
#: No second, stricter tier is reported. A "strong binder" cutoff of rank <= 2 is
#: widely quoted, but IEDB's own guidance gives numeric cutoffs only in IC50 nM
#: (50 / 500 / 5000) and points elsewhere for rank thresholds, so no rank-based
#: strong-binder cutoff could be traced to a source. Rather than ship a number
#: from memory, the full rank is reported per epitope and the caller can threshold.
BINDER_RANK = 10.0

#: The junctional window per chain type: IMGT positions after the furthest reach
#: of any germline V allele and before the earliest start of any germline J
#: allele. Derived from ANARCI's germline set at import time.
#:
#: Nothing in this window can be classified by the germline definition of self.
#: It is encoded by the D segment (heavy chains) plus nucleotides added at random
#: during recombination, and a germline D gene has no single protein sequence: a
#: D segment is used in any of six reading frames and is trimmed by a variable
#: number of nucleotides at each end, so the same gene yields different amino
#: acids in different rearrangements. That is why neither ANARCI nor IMGT's
#: amino-acid reference ships D protein sequences.
#:
#: Treating this window as "not germline-encoded, therefore unmatched" would
#: overstate the burden exactly where the metric is most sensitive. Peptides here
#: are reported as unclassifiable by germline; the repertoire definition, which
#: is built from real rearranged sequences, is the one that applies.
JUNCTIONAL_WINDOW = {"H": (108, 114), "K": (109, 115), "L": (109, 115)}

#: Sentinel for "two or more residues from the nearest reference peptide". The
#: exact distance beyond one is not computed and nothing downstream needs it, so
#: this value must be read as "2 or more" and never printed as an exact 2.
FAR = 2

#: How far a core must be from the nearest reference peptide to be *unmatched*.
#:
#: 1, meaning: anything that is not an exact match to the reference counts. This
#: is the headline comparison, and it is deliberately the weakest claim the data
#: supports -- "this core is not in the reference set" is an observation about a
#: lookup. Immunology begins after it.
#:
#: An earlier default of 2 excluded one-substitution variants on the reasoning
#: that a single change often leaves the T-cell receptor contacts intact. That
#: is plausible and it is not established: whether a substitution matters
#: depends on which position it hits and what it changes. The number of changes
#: settles nothing on its own, so one mismatch carries no evidence of lower risk
#: than two, and a count assuming it does presents a hypothesis as a measurement.
UNMATCHED_THRESHOLD = 1

#: The same count with one-substitution variants excluded, kept as an explicitly
#: exploratory sensitivity analysis and never as the headline. Reported beside
#: the main count so the size of the assumption is visible rather than argued.
DISTANT_THRESHOLD = 2

SelfDefinition = Literal["germline", "repertoire", "proteome"]
SELF_DEFINITIONS: tuple[SelfDefinition, ...] = ("germline", "repertoire", "proteome")

#: Plain-language names for the reference sets, for display. "unmatched" and
#: "germline" are precise and opaque; a reader should not have to learn the
#: codebase's vocabulary to read a report.
REFERENCE_LABELS = {
    "germline": "germline Ig genes",
    "repertoire": "OAS repertoire",
    "proteome": "human proteome",
}

SELF_DEFINITION_NOTES = {
    "germline": "peptide core occurs in a human germline Ig V or J allele",
    "repertoire": "peptide core occurs in human antibody repertoires (OAS, >=10% of donors)",
    "proteome": "peptide core occurs anywhere in the human reference proteome",
}


@lru_cache(maxsize=1)
def germline_peptide_source(core_length: int = 9) -> frozenset[str]:
    """Every `core_length`-mer appearing in any human germline Ig V or J allele.

    Built from ANARCI's bundled IMGT germline set, over all three chain types and
    both segments, with IMGT gaps removed first so that peptides spanning a
    gapped position are still generated. J segments are included because FR4 is
    J-encoded, and a framework peptide there is no less self than one in FR1.
    """
    from anarci.germlines import all_germlines

    peptides: set[str] = set()
    for segment in ("V", "J"):
        for chain in ("H", "K", "L"):
            alleles = all_germlines.get(segment, {}).get(chain, {}).get("human", {})
            for gapped in alleles.values():
                sequence = gapped.replace("-", "").replace(".", "")
                for start in range(len(sequence) - core_length + 1):
                    peptides.add(sequence[start : start + core_length])
    return frozenset(peptides)


@dataclass(frozen=True)
class Epitope:
    """One predicted binder, located and classified against self."""

    binding: Binding
    positions: tuple[Position, ...]
    # Stored as a tuple of pairs rather than a dict so the dataclass stays
    # hashable: a frozen dataclass derives __hash__ from its fields, and a dict
    # field makes instances unhashable, which breaks set operations on epitopes.
    self_distances: tuple[tuple[str, int], ...]
    chain_type: str = "H"

    @property
    def allele(self) -> str:
        return self.binding.allele

    @property
    def peptide(self) -> str:
        return self.binding.peptide

    @property
    def core(self) -> str:
        return self.binding.core

    @property
    def rank(self) -> float:
        return self.binding.rank

    @property
    def is_junctional(self) -> bool:
        """True if the core overlaps the junctional window.

        The germline definition of self cannot classify these: the window is
        encoded by a D segment read in one of six frames plus randomly added
        nucleotides, so no germline protein reference exists for it. See
        JUNCTIONAL_WINDOW.
        """
        low, high = JUNCTIONAL_WINDOW.get(self.chain_type, (0, -1))
        return any(low <= p[0] <= high for p in (self.core_positions or self.positions))

    @property
    def distances(self) -> dict[str, int]:
        """Self-distance per definition, as a mapping."""
        return dict(self.self_distances)

    def distance_to_reference(self, definition: SelfDefinition = "germline") -> int:
        """Residues to the nearest reference peptide: 0, 1, or FAR (meaning 2+)."""
        return self.distances.get(definition, FAR)

    def distance_label(self, definition: SelfDefinition = "germline") -> str:
        """The distance as it may be displayed: "0", "1" or "2+", never "2".

        Distances beyond one are not computed, so printing a bare 2 would claim
        a precision that does not exist.
        """
        if self.is_unclassifiable(definition):
            return "n/a"
        distance = self.distance_to_reference(definition)
        return "2+" if distance >= FAR else str(distance)

    def matches_reference(self, definition: SelfDefinition = "germline") -> bool:
        """An exact match to a peptide in the reference set.

        A match means the lookup found it. It does not establish that a patient
        is tolerant to it: tolerance is incomplete, and the reference set is not
        that patient.
        """
        return self.distance_to_reference(definition) == 0

    def is_one_substitution(self, definition: SelfDefinition = "germline") -> bool:
        """Unmatched, with the nearest reference peptide one substitution away.

        Counted as unmatched. Kept as an annotation because the distance is
        informative. Whether one mismatch is safer than two remains unknown.
        """
        return self.distance_to_reference(definition) == 1

    def is_unmatched(
        self,
        definition: SelfDefinition = "germline",
        threshold: int = UNMATCHED_THRESHOLD,
    ) -> bool:
        """No exact match in the reference set under `definition`.

        A junctional core is never reported as unmatched by the germline
        definition, because that definition cannot classify it either way -- see
        `is_unclassifiable`. The repertoire definition, built from real
        rearranged sequences, does apply there.

        `threshold` is how many residues from the nearest reference peptide a
        core must be. The default of 1 counts everything that is not an exact
        match. Passing DISTANT_THRESHOLD excludes one-substitution variants,
        which is an exploratory sensitivity analysis and not the headline.
        """
        if definition == "germline" and self.is_junctional:
            return False
        return self.distance_to_reference(definition) >= threshold

    def is_unclassifiable(self, definition: SelfDefinition = "germline") -> bool:
        """True when `definition` has no reference for this peptide."""
        return definition == "germline" and self.is_junctional

    @property
    def regions(self) -> tuple[str, ...]:
        seen: list[str] = []
        for position in self.positions:
            region = region_of_position(position)
            if region is not None and region not in seen:
                seen.append(region)
        return tuple(seen)

    @property
    def touches_cdr(self) -> bool:
        return any(region in CDR_REGIONS for region in self.regions)

    @property
    def core_positions(self) -> tuple[Position, ...]:
        """IMGT positions of the 9-mer core, if it can be located in the peptide."""
        if not self.core or self.core not in self.peptide:
            return ()
        offset = self.peptide.index(self.core)
        return self.positions[offset : offset + len(self.core)]


@dataclass(frozen=True)
class EpitopeBurden:
    """Predicted class II epitopes for one chain, classified against self."""

    epitopes: tuple[Epitope, ...]
    alleles: tuple[str, ...]
    method: str
    peptide_length: int
    binder_rank: float
    chain_type: str
    n_predictions: int
    mismatch_threshold: int = UNMATCHED_THRESHOLD
    domain_warnings: tuple[str, ...] = ()

    @property
    def binders(self) -> tuple[Epitope, ...]:
        return self.epitopes

    def binders_below_rank(self, rank: float) -> tuple[Epitope, ...]:
        """Binders at a caller-chosen rank cutoff.

        Offered instead of a built-in "strong binder" tier, because no
        rank-based strong-binder cutoff could be traced to an IEDB source.
        """
        return tuple(e for e in self.epitopes if e.rank <= rank)

    @property
    def effective_threshold(self) -> int:
        """The one distance threshold every count on this burden uses.

        There is exactly one, and it is the stored field. An earlier version
        defaulted these methods to the module constant while provenance
        reported the stored value, so a burden could advertise a threshold of 3
        and still count at 2 -- a report whose stated settings did not produce
        its own numbers.
        """
        return self.mismatch_threshold

    def unmatched(
        self,
        definition: SelfDefinition = "germline",
        threshold: int | None = None,
    ) -> tuple[Epitope, ...]:
        """Binders with no exact match in the reference set.

        The headline reference comparison. `threshold=None` means this burden's
        own threshold, which defaults to 1 -- everything that is not an exact
        match. An explicit value is for a named sensitivity analysis and never
        silently differs from what provenance reports.
        """
        effective = self.effective_threshold if threshold is None else threshold
        return tuple(e for e in self.epitopes if e.is_unmatched(definition, effective))

    def matched(self, definition: SelfDefinition = "germline") -> tuple[Epitope, ...]:
        """Binders that are exactly present in the reference set."""
        return tuple(e for e in self.epitopes if e.matches_reference(definition))

    def one_substitution(self, definition: SelfDefinition = "germline") -> tuple[Epitope, ...]:
        """Unmatched binders whose nearest reference peptide is one substitution away."""
        return tuple(e for e in self.epitopes if e.is_one_substitution(definition))

    def distant(self, definition: SelfDefinition = "germline") -> tuple[Epitope, ...]:
        """Unmatched binders at least DISTANT_THRESHOLD from the reference.

        **Exploratory.** Excluding one-substitution variants assumes a single
        change leaves a core recognisably self, which depends on which position
        changed and is not established here. Reported beside the main count, not
        instead of it.
        """
        return tuple(e for e in self.epitopes if e.is_unmatched(definition, DISTANT_THRESHOLD))

    def count(self, definition: SelfDefinition | None = None) -> int:
        """Binder count: every predicted hit if `definition` is None, else the
        unmatched hits under that reference."""
        return len(self.epitopes) if definition is None else len(self.unmatched(definition))

    def unclassifiable(self, definition: SelfDefinition = "germline") -> tuple[Epitope, ...]:
        """Binders this reference has no entry to compare against, either way."""
        return tuple(e for e in self.epitopes if e.is_unclassifiable(definition))

    def counts_by_definition(self) -> dict[str, int]:
        """Every count, per reference set.

        For each definition the three categories partition the predicted hits:

            matched + unmatched + unclassifiable == raw

        `unmatched` is the headline. `one_substitution` and `distant` are
        subsets of it, annotations rather than further categories, and they sum
        back to it. `unclassifiable` is only ever non-zero for germline.
        """
        counts = {
            "raw": len(self.epitopes),
            "distinct_cores": len(self.unique_cores(None)),
        }
        for definition in SELF_DEFINITIONS:
            counts[f"{definition}_matched"] = len(self.matched(definition))
            counts[f"{definition}_unmatched"] = len(self.unmatched(definition))
            counts[f"{definition}_one_substitution"] = len(self.one_substitution(definition))
            counts[f"{definition}_distant"] = len(self.distant(definition))
            counts[f"{definition}_unclassifiable"] = len(self.unclassifiable(definition))
        return counts

    def core_counts_by_definition(self) -> dict[str, int]:
        """The same counts, over distinct 9-mer cores instead of hits.

        The unit matters more than it looks. A hit is one peptide-allele pair,
        so the same core is counted once per allele that presents it and once
        per overlapping 15-mer window it falls in: on trastuzumab the germline
        framework motif YLQMNSLRA accounts for 27 of 86 hits by itself. A count
        of hits therefore partly measures how many alleles happen to present the
        same peptide, which is a property of that peptide rather than a number
        of distinct risks.

        Cores are the actionable unit -- how many distinct peptides there are to
        look at -- and hits are the breadth, how widely each is presented. Both
        are reported, labelled, and never silently swapped.
        """
        cores = {e.core for e in self.epitopes if e.core}
        counts = {"raw": len(cores), "distinct_cores": len(cores)}
        for definition in SELF_DEFINITIONS:
            counts[f"{definition}_matched"] = len(
                {e.core for e in self.matched(definition) if e.core}
            )
            counts[f"{definition}_unmatched"] = len(
                {e.core for e in self.unmatched(definition) if e.core}
            )
            counts[f"{definition}_one_substitution"] = len(
                {e.core for e in self.one_substitution(definition) if e.core}
            )
            counts[f"{definition}_distant"] = len(
                {e.core for e in self.distant(definition) if e.core}
            )
            counts[f"{definition}_unclassifiable"] = len(
                {e.core for e in self.unclassifiable(definition) if e.core}
            )
        return counts

    def counts_by_allele(self, definition: SelfDefinition | None = "germline") -> dict[str, int]:
        """Per-allele burden. No frequency weighting is applied; see `weighted`."""
        pool = self.epitopes if definition is None else self.unmatched(definition)
        counts = dict.fromkeys(self.alleles, 0)
        for epitope in pool:
            counts[epitope.allele] = counts.get(epitope.allele, 0) + 1
        return counts

    def counts_by_region(self, definition: SelfDefinition | None = "germline") -> dict[str, int]:
        """Where the burden sits. A peptide spanning two regions counts in both."""
        pool = self.epitopes if definition is None else self.unmatched(definition)
        counts: dict[str, int] = {}
        for epitope in pool:
            for region in epitope.regions:
                counts[region] = counts.get(region, 0) + 1
        return counts

    def unique_cores(self, definition: SelfDefinition | None = "germline") -> tuple[str, ...]:
        """Distinct 9-mer cores, so one peptide binding six alleles counts once.

        The raw binder count conflates "how many peptides are risky" with "how
        many alleles present them". Both matter and they are different numbers.
        """
        pool = self.epitopes if definition is None else self.unmatched(definition)
        return tuple(sorted({e.core for e in pool if e.core}))

    def weighted_burden(
        self,
        allele_frequencies: dict[str, float],
        definition: SelfDefinition = "germline",
    ) -> float:
        """Unmatched burden weighted by caller-supplied allele frequencies.

        No frequency table is shipped. HLA allele frequencies vary by an order of
        magnitude between populations, every published set is specific to the
        cohort it was measured in, and shipping one unverified would put a number
        in a report that cannot be traced. The caller supplies frequencies for
        the population they care about, and the report records them.
        """
        unknown = sorted(set(allele_frequencies) - set(self.alleles))
        if unknown:
            raise KeyError(f"frequencies given for alleles not in the panel: {unknown}")
        counts = self.counts_by_allele(definition)
        return sum(counts[allele] * allele_frequencies.get(allele, 0.0) for allele in self.alleles)

    def provenance(self) -> dict[str, object]:
        from .iedb import service_provenance

        record = dict(
            service_provenance(
                self.method,
                peptide_length=self.peptide_length,
                alleles=self.alleles,
            )
        )
        record.update(
            {
                "binder_percentile_rank_cutoff": self.binder_rank,
                "binder_cutoff_source": (
                    "10th percentile, as used in Prihoda et al., MAbs 2022. No "
                    "stricter tier is reported: IEDB's guidance gives numeric "
                    "cutoffs only in IC50 nM, so no rank-based strong-binder "
                    "threshold could be traced to a source."
                ),
                "junctional_window_imgt": {
                    chain: list(bounds) for chain, bounds in JUNCTIONAL_WINDOW.items()
                },
                "self_definitions": dict(SELF_DEFINITION_NOTES),
                "unmatched_threshold": self.mismatch_threshold,
                "threshold_rationale": (
                    "The headline count is every predicted core with no exact "
                    "match in the chosen reference set (threshold 1). One "
                    "mismatch is NOT treated as safer than two: whether a "
                    "substitution matters depends on which position it hits, "
                    "which this does not model. The distance is kept as an "
                    "annotation (0, 1, 2+) and the count excluding "
                    "one-substitution variants is reported separately as "
                    "*_distant, an exploratory sensitivity analysis only. For "
                    "scale: a human lambda chain at 95.4% germline identity, "
                    "carrying four somatic mutations, gave 28 unmatched cores, "
                    "every one of them exactly one residue from germline -- "
                    "which is why the distance is shown rather than discarded, "
                    "and why discarding it is not the default."
                ),
                "count_reconciliation": (
                    "Per reference set, matched + unmatched + unclassifiable == "
                    "raw predicted hits. one_substitution and distant are "
                    "subsets of unmatched and sum back to it. unclassifiable is "
                    "non-zero only for germline, which has no reference for the "
                    "junctional window."
                ),
                "germline_self_peptide_count": len(germline_peptide_source()),
                "predictions_returned": self.n_predictions,
                "frequency_weighting": (
                    "not applied by default; no HLA allele frequency table is "
                    "shipped because frequencies are population-specific and none "
                    "could be verified to a citable source"
                ),
            }
        )
        return record

    def warnings(self) -> tuple[str, ...]:
        messages = list(self.domain_warnings)
        if any(m.startswith(PARTIAL_DOMAIN_PREFIX) for m in self.domain_warnings):
            messages.append(
                "epitope burden computed on a partial domain: fewer windows were "
                "scored than for a complete chain, so the count is not directly "
                "comparable."
            )
        return tuple(messages)


def _point_mutants(peptide: str):
    """Every single-substitution variant of `peptide`."""
    for index, original in enumerate(peptide):
        for residue in STANDARD_RESIDUES:
            if residue != original:
                yield peptide[:index] + residue + peptide[index + 1 :]


def self_distance(core: str, definition: SelfDefinition) -> int:
    """Residues between this core and the nearest self peptide.

    Returns 0 (the peptide IS self), 1 (one substitution away), or
    FAR (two or more -- the exact distance is not computed, because nothing
    downstream distinguishes three mismatches from seven).

    Distance rather than a yes/no, because exact matching is wrong here. T-cell
    tolerance is not binary: a single substitution often leaves the residues a
    T-cell receptor contacts unchanged, so a one-off variant of a self peptide is
    not reliably a new epitope. Treating it as fully foreign inflates the count
    on every affinity-matured antibody -- which is nearly every real one.

    Measured on two real chains: a pristine human lambda chain at 95.4% germline
    identity, carrying just four somatic mutations, produced 28 unmatched
    binders under exact matching, and all five of their distinct cores were
    exactly one residue from a germline peptide.

    The core is used rather than the full 15-mer because the core is what sits in
    the binding groove and determines which T-cell receptors can see the complex.
    """
    if not core:
        return FAR

    if definition == "germline":
        source = germline_peptide_source(len(core))
        if core in source:
            return 0
        return 1 if any(m in source for m in _point_mutants(core)) else FAR

    if definition == "repertoire":
        db = get_database("human-oas")
    elif definition == "proteome":
        db = get_database("human-reference", len(core))
    else:
        raise ValueError(f"unknown self definition {definition!r}")

    if db.contains(core):
        return 0
    return 1 if db.contains_or_point_mutant(core) else FAR


def _classify(core: str) -> tuple[tuple[str, int], ...]:
    return tuple((d, self_distance(core, d)) for d in SELF_DEFINITIONS)


def epitope_burden(
    domain: Domain,
    *,
    alleles: tuple[str, ...] = DEFAULT_ALLELES,
    method: str = DEFAULT_METHOD,
    peptide_length: int = DEFAULT_PEPTIDE_LENGTH,
    binder_rank: float = BINDER_RANK,
    cache_dir: str | None = None,
    offline: bool = False,
    progress: Callable[[str], None] | None = None,
) -> EpitopeBurden:
    """Predict class II binders for a numbered domain and classify them.

    The sequence sent to IEDB is the domain's own residues in IMGT order, so the
    1-based `start` IEDB returns indexes straight into that ordered list and each
    peptide can be placed in IMGT coordinates.
    """
    ordered = sorted(domain.numbering, key=imgt_sort_key)
    kwargs: dict = {
        "alleles": alleles,
        "method": method,
        "peptide_length": peptide_length,
        "offline": offline,
    }
    if progress is not None:
        kwargs["progress"] = progress
    if cache_dir is not None:
        kwargs["cache_dir"] = cache_dir

    predictions = predict_mhcii(domain.seq, **kwargs)

    classified: dict[str, tuple[tuple[str, int], ...]] = {}
    epitopes: list[Epitope] = []
    for binding in predictions:
        if binding.rank > binder_rank:
            continue
        start = max(binding.start - 1, 0)
        positions = tuple(ordered[start : start + len(binding.peptide)])
        if binding.core not in classified:
            classified[binding.core] = _classify(binding.core)
        epitopes.append(
            Epitope(
                binding=binding,
                positions=positions,
                self_distances=classified[binding.core],
                chain_type=domain.chain_type,
            )
        )

    epitopes.sort(key=lambda e: (e.rank, e.allele))
    return EpitopeBurden(
        epitopes=tuple(epitopes),
        alleles=tuple(alleles),
        method=method,
        peptide_length=peptide_length,
        binder_rank=binder_rank,
        chain_type=domain.chain_type,
        n_predictions=len(predictions),
        domain_warnings=domain.warnings,
    )


def epitope_burden_for_sequence(sequence: str, **kwargs) -> EpitopeBurden:
    """Number `sequence` and compute the epitope burden for its single domain."""
    from .number import number_single_chain

    return epitope_burden(number_single_chain(sequence), **kwargs)
