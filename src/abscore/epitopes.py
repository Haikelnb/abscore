"""MHC class II predicted-binder burden, compared against a human reference.

What is counted, in one line
----------------------------
Predicted peptide-allele hits, and then how many of their 9-mer cores are *not
found* in a chosen human reference set. "Unmatched" is a statement about a
lookup. Whether a peptide is foreign, immunogenic or untolerated stays open, and
so does whether any given patient is tolerant to a matched one.

Three units are reported and they are different numbers: predicted hits (one per
peptide-allele pair), distinct cores (one peptide presented by six alleles is one
core), and unmatched hits. None of them is a count of experimentally confirmed
epitopes.

Why the reference comparison is worth making anyway
---------------------------------------------------
A CD4 T cell responds to a peptide presented on MHC class II only if a T cell
bearing a receptor for that peptide survived thymic selection. T cells reactive
to peptides from the body's own proteins are largely deleted there, or diverted
into regulatory T cells. So a peptide that is part of normal human protein
sequence has, for the most part, no available T cell to recognise it.

A germline-encoded antibody framework peptide is such a peptide: it is encoded in
the patient's own genome and displayed by their own B cells. Predicting that it
binds MHC II says nothing about immunogenicity risk.

Concretely. On trastuzumab, the single strongest predicted
binder across the eight-allele panel is `NTAYLQMNSLRAEDT` (core `YLQMNSLRA`,
HLA-DRB1*04:01, percentile rank 0.01) -- a conserved framework 3 motif carried by
human IGHV3 germline genes. Counted naively it is the top risk in the molecule.
Filtered against self, it disappears.

So the interesting peptides are the ones a human reference does *not* contain:
the CDRs, especially the junctional CDR3, and positions altered by somatic
mutation or by engineering.

How far that argument carries
-----------------------------
Only this far. Tolerance is incomplete -- self-reactive T cells persist in
healthy people, which is what makes autoimmunity possible -- so reference
membership lowers a peptide's priority rather than clearing it. And the reverse
does not follow either: a human sequence can have many predicted hits, and a
peptide absent from a reference set is not thereby shown to be recognised.

This is also why distance from the reference is reported but not used to
discount anything by default. A core one substitution from a germline peptide
may or may not matter: it depends on which position changed and whether a T-cell
receptor contacts it, which is not modelled here. Treating one mismatch as safer
than two would be a hypothesis presented as a measurement. The distance is kept
as an annotation (0, 1, 2+), and the count that excludes one-substitution
variants is available as an explicitly exploratory sensitivity analysis.

What "the reference" means, and why three are reported
------------------------------------------------------
The choice is a judgement call, so all three are computed and the count is
reported under each:

- `germline`   the peptide occurs in a human germline immunoglobulin V or J
               allele. The narrowest definition and the one tied most directly
               to the tolerance argument above.
- `repertoire` the peptide occurs in human antibody repertoires (OAS). Broader:
               it also excuses commonly occurring somatic mutations, which are
               plausibly tolerated because many people present them.
- `proteome`   the peptide occurs anywhere in the human proteome. Broadest and
               arguably most correct -- a peptide identical to a stretch of human
               serum albumin is self whether or not it is an antibody peptide.

Showing how the burden moves between these is better evidence than picking one
and hiding the choice. They disagree by nearly twofold on the same chain, and
that spread is the honest size of the uncertainty in the metric.

What this does not establish
----------------------------
Each link in the chain loses information, and only the first is modelled:

    predicted binding -> actual binding -> the peptide is actually generated by
    proteolytic processing -> it is actually presented on a cell surface -> a
    CD4 T cell with a matching receptor exists in this patient and escaped
    tolerance -> it is not suppressed by regulatory T cells -> a response develops

Also: HLA-DRB1 only, so DP and DQ are unmodelled; no processing model; no
regulatory T cell model. Clinical anti-drug antibody risk is additionally driven
by aggregation, dose, route, formulation and patient population, none of which a
sequence can show. This is triage ahead of ex vivo T cell assays and MHC-associated
peptide proteomics, deciding where to spend one.
"""

